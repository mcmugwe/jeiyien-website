CREATE TABLE IF NOT EXISTS projects (
 id TEXT PRIMARY KEY, title TEXT NOT NULL, description TEXT NOT NULL DEFAULT '',
 category TEXT NOT NULL DEFAULT 'road', location TEXT NOT NULL DEFAULT '',
 year TEXT NOT NULL DEFAULT '', duration TEXT NOT NULL DEFAULT '',
 image TEXT NOT NULL, alt TEXT NOT NULL DEFAULT '',
 gallery_json TEXT NOT NULL DEFAULT '[]', published INTEGER NOT NULL DEFAULT 1,
 sort_order INTEGER NOT NULL DEFAULT 0, updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS banners (
 id TEXT PRIMARY KEY, image TEXT NOT NULL, alt TEXT NOT NULL DEFAULT '',
 active INTEGER NOT NULL DEFAULT 0, sort_order INTEGER NOT NULL DEFAULT 0,
 updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
